-- Eliminación física solo cuando no existe ninguna relación operativa o histórica.
delete from public.productos p
where not exists (
 select 1 from app_catalogo_vigente v where lower(btrim(v.codigo))=lower(btrim(p.codigo))
)
and not exists (select 1 from public.lotes l where l.producto_id=p.id)
and not exists (select 1 from public.inventario i where i.producto_id=p.id)
and not exists (select 1 from public.inventario_minimos m where m.producto_id=p.id)
and not exists (select 1 from public.movimientos m where m.producto_id=p.id)
and not exists (select 1 from public.recepcion_detalles d where d.producto_id=p.id)
and not exists (select 1 from public.proveedor_productos pp where pp.producto_id=p.id);

-- Los productos fuera de la lista que conservan historial se ocultan del catálogo operativo.
update public.productos p
set estado=false
where not exists (
 select 1 from app_catalogo_vigente v where lower(btrim(v.codigo))=lower(btrim(p.codigo))
)
and p.estado is distinct from false;

-- La lista nueva queda activa.
update public.productos p
set estado=true
where exists (
 select 1 from app_catalogo_vigente v where lower(btrim(v.codigo))=lower(btrim(p.codigo))
)
and p.estado is distinct from true;

commit;

-- Verificación independiente. El catálogo vigente debe mostrar 270 activos y 0 activos fuera de la lista.
select
 count(*) filter (
  where estado and upper(btrim(codigo)) ~ '^(A|C|D|E|F|G|H|I|L|O|P|T)-[0-9]{3}$'
 ) as catalogo_nuevo_activo,
 count(*) filter (
  where estado and upper(btrim(codigo)) !~ '^(A|C|D|E|F|G|H|I|L|O|P|T)-[0-9]{3}$'
 ) as fuera_lista_activos,
 count(*) filter (
  where not estado and upper(btrim(codigo)) !~ '^(A|C|D|E|F|G|H|I|L|O|P|T)-[0-9]{3}$'
 ) as historicos_inactivos
from public.productos;

